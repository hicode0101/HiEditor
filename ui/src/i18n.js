const DICT = { "zh-CN": ZH, "en-US": EN };

let eff = "zh-CN";

function autoDetect() {
  const nav = (navigator.language || "zh").toLowerCase();
  return nav.startsWith("zh") ? "zh-CN" : "en-US";
}

/** pref: "auto" | "zh-CN" | "en-US" */
export function setLanguage(pref) {
  eff = pref && pref !== "auto" && DICT[pref] ? pref : autoDetect();
  document.documentElement.lang = eff;
}

export function effectiveLang() {
  return eff;
}

export function t(key, params) {
  const d = DICT[eff] || DICT["zh-CN"];
  let s = d[key] ?? DICT["zh-CN"][key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}

/** 把静态 DOM 上带 data-i18n / data-i18n-title 的元素全部刷新为当前语言 */
export function applyI18n() {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
  });
  document.documentElement.lang = eff;
}
